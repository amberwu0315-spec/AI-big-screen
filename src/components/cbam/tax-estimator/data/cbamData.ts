// 搜索结果接口
export interface CBAMSearchResult {
  cnCode: string;
  productName: string;
  category: string;
  item: CBAMItem;
}

// 搜索CBAM商品（支持CN编码和中文产品名称搜索）
export const searchCBAMItems = (query: string, limit?: number): CBAMSearchResult[] => {
  const trimmedQuery = query.trim();

  if (!trimmedQuery || trimmedQuery.length < 2) return [];

  const normalizedQuery = trimmedQuery.toLowerCase();

  const results = cbamData
    .map((item) => {
      const productName = getProductName(item.cnCode);
      const cnCodeMatch = item.cnCode.toLowerCase().includes(normalizedQuery);
      const productNameMatch = productName.toLowerCase().includes(normalizedQuery);
      const categoryMatch = item.category.toLowerCase().includes(normalizedQuery);

      if (cnCodeMatch || productNameMatch || categoryMatch) {
        return {
          cnCode: item.cnCode,
          productName,
          category: item.category,
          item,
          // 优先级：CN编码完全匹配 > CN编码前缀匹配 > 产品名称匹配 > 类别匹配
          priority: item.cnCode.toLowerCase().startsWith(normalizedQuery)
            ? 0
            : cnCodeMatch
              ? 1
              : productNameMatch
                ? 2
                : 3,
        };
      }
      return null;
    })
    .filter((result): result is NonNullable<typeof result> => result !== null)
    .sort((a, b) => a.priority - b.priority);

  return limit ? results.slice(0, limit) : results;
};
